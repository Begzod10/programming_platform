async def main() -> None:
    async with AsyncSessionLocal() as db:
        result = await db.execute(
            select(GameQuestion).where(
                GameQuestion.question_kind == "quiz",
                GameQuestion.session_id == SESSION_ID,
                or_(GameQuestion.question_text_ru.is_(None), GameQuestion.question_text_ru == "", GameQuestion.options_ru.is_(None)),
            ).order_by(GameQuestion.id)
        )
        rows = result.scalars().all()
        print(f"Batch B (session 99): {len(rows)} rows need RU")

        written = 0
        for row in rows:
            tr = ROW_TRANSLATIONS.get(row.id)
            if tr is None:
                print(f"  SKIP id={row.id}: no translation prepared")
                continue
            q_ru, opts_ru = tr
            if len(opts_ru) != len(row.options):
                print(f"  SKIP id={row.id}: option count mismatch ({len(opts_ru)} vs {len(row.options)})")
                continue
            row.question_text_ru = q_ru
            row.options_ru = opts_ru
            written += 1
        await db.commit()
        print(f"Batch B wrote {written}/{len(rows)} rows.")


if __name__ == "__main__":
    asyncio.run(main())
